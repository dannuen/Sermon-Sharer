"""Regenerates src/fonts-data.ts: every font the card templates use, subset to
Latin + Vietnamese and inlined as base64 woff2.

Two sources:
  1. Google Fonts CSS files in fonts/*.css (Playfair Display, Be Vietnam Pro):
     their per-subset woff2 files are downloaded as-is.
  2. Local font files in fonts/src/ (Inter FFS, Addington CF, Cormorant Garamond,
     EB Garamond, Be Vietnam Pro Medium): subset with fontTools (pip install fonttools brotli).

Run from the plugin folder:  python3 scripts/gen-fonts.py
"""
import base64, io, json, os, re, sys, urllib.request

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = []

# 1. Google Fonts subsets --------------------------------------------------
for css in ["fonts/Playfair_Display_ital_wght_0_700_1_400.css", "fonts/Be_Vietnam_Pro_wght_400_600.css"]:
    txt = open(css).read()
    for subset, body in re.findall(r"/\* (\w[\w-]*) \*/\s*@font-face \{(.*?)\}", txt, re.S):
        if subset not in ("vietnamese", "latin", "latin-ext"):
            continue
        fam = re.search(r"font-family: '([^']+)'", body).group(1)
        style = re.search(r"font-style: (\w+)", body).group(1)
        weight = re.search(r"font-weight: (\d+)", body).group(1)
        url = re.search(r"url\(([^)]+)\)", body).group(1)
        ur = re.search(r"unicode-range: ([^;]+);", body).group(1)
        data = urllib.request.urlopen(url).read()
        out.append(dict(family=fam, style=style, weight=int(weight), subset=subset, unicodeRange=ur,
                        data=base64.b64encode(data).decode()))
        print(fam, style, weight, subset, len(data))

# 2. Local files, subset to Latin + Vietnamese ------------------------------
LOCAL = [
    # file, family, style, weight
    ("fonts/src/InterFFS-Regular.ttf", "Inter FFS", "normal", 400),
    ("fonts/src/InterFFS-Medium.ttf", "Inter FFS", "normal", 500),
    ("fonts/src/AddingtonCF-RegularItalic.otf", "Addington CF", "italic", 400),
    ("fonts/src/CormorantGaramond-SemiBold.ttf", "Cormorant Garamond", "normal", 600),
    ("fonts/src/EBGaramond-Regular.ttf", "EB Garamond", "normal", 400),
    ("fonts/src/EBGaramond-Italic.ttf", "EB Garamond", "italic", 400),
    ("fonts/src/BeVietnamPro-Medium.ttf", "Be Vietnam Pro", "normal", 500),
]
UNICODES = "U+0000-00FF,U+0100-024F,U+0300-036F,U+1EA0-1EF9,U+2000-206F,U+20AB,U+2122,U+2190-2199"
RANGE_CSS = "U+0000-00FF, U+0100-024F, U+0300-036F, U+1EA0-1EF9, U+2000-206F, U+20AB, U+2122"
try:
    from fontTools import subset as ftsubset
    from fontTools.ttLib import TTFont
except ImportError:
    sys.exit("fontTools is required for the local fonts: pip install fonttools brotli")

for path, fam, style, weight in LOCAL:
    if not os.path.exists(path):
        print("missing", path); continue
    font = TTFont(path)
    opts = ftsubset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = ftsubset.Subsetter(options=opts)
    sub.populate(unicodes=ftsubset.parse_unicodes(UNICODES))
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    data = buf.getvalue()
    out.append(dict(family=fam, style=style, weight=weight, subset="latin+vietnamese", unicodeRange=RANGE_CSS,
                    data=base64.b64encode(data).decode()))
    print(fam, style, weight, "subset", len(data))

with open("src/fonts-data.ts", "w") as f:
    f.write("// Generated by scripts/gen-fonts.py. Do not edit by hand.\n")
    f.write("// Playfair Display, Be Vietnam Pro, Cormorant Garamond, EB Garamond: SIL Open Font License.\n")
    f.write("// Inter FFS: Inter (OFL) build. Addington CF: licensed to the vault owner; do not redistribute.\n")
    f.write("export interface FontEntry { family: string; style: string; weight: number; subset: string; unicodeRange: string; data: string }\n")
    f.write("export const FONTS: FontEntry[] = " + json.dumps(out, indent=0) + ";\n")
print("total b64 bytes", sum(len(o["data"]) for o in out))
